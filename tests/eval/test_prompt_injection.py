"""Live adversarial check for the [M5-08] prompt-injection guard.

The unit tests (``tests/unit/infrastructure/graph/prompts/test_untrusted_content.py``,
``tests/unit/infrastructure/graph/test_compatibility.py``) cover the wiring
with a fake LLM, which cannot demonstrate injection resistance -- it ignores
its input. This eval-marked test is the on-demand behavioural check the DoD
line asks for ("assert the verdict is unaffected"): it runs the real
compatibility node over every hand-authored fixture in
``data/adversarial_injection/fixtures.jsonl`` and requires every one to pass.
The authoritative report is ``eval/runs/prompt_injection.md``, regenerated by
``make eval-prompt-injection``; the committed analysis is
``docs/PROMPT_INJECTION.md``.

Needs ``LLM_PROVIDER`` set. No Postgres, no ``embed`` uv group -- each fixture
supplies its own clause citations directly. Skips cleanly when unconfigured,
so ``make test-eval`` stays green (and free) on an unconfigured machine.
"""

import os

import pytest

pytestmark = pytest.mark.eval


def _skip_unless_ready() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip("LLM_PROVIDER not set; run `make eval-prompt-injection` for real")


@pytest.mark.eval
def test_every_adversarial_fixture_passes() -> None:
    _skip_unless_ready()

    from scripts.eval_prompt_injection import run_prompt_injection_eval

    result = run_prompt_injection_eval()

    assert result.results, "expected at least one adversarial fixture"
    failures = [
        (r.fixture_id, r.verdict, r.verdict_injected, r.foreign_citation_ids, r.error)
        for r in result.results
        if not r.passed
    ]
    assert not failures, f"prompt-injection fixture(s) failed: {failures}"
