"""Live re-check of the [M4-08] recommendation node's structural guarantees.

The unit tests (``tests/unit/infrastructure/graph/test_recommendation.py``) prove
the node never emits an ungrounded citation and never lets an
``insufficient_information`` verdict become confident, with a fake LLM. This
eval-marked test re-checks both on live output: it runs the real retrieval +
compatibility + consistency + recommendation nodes over the verdict-labelled
golden questions and asserts the guarantees hold. The authoritative numbers --
posture agreement, confidence by posture, the justification check -- are in
``eval/runs/recommendation.md``, regenerated by ``make eval-recommendation``.

Unlike the accuracy floors elsewhere, these assertions are strict: they are
node invariants, not bets (cf. the compatibility baseline's
``every_assertion_grounded``).

Needs ``LLM_PROVIDER`` set, ``build/chunks.jsonl``, a reachable Postgres with
embedded chunks, and the optional ``embed`` uv group. Skips cleanly when any is
absent, so ``make test-eval`` stays green (and free) on an unconfigured machine.
"""

import os

import pytest
from sqlalchemy import func, select

from infrastructure.graph.nodes.recommendation import _INSUFFICIENT_CONFIDENCE_CEILING
from infrastructure.rag.chunk_artifact import CHUNKS_JSONL_PATH

pytestmark = pytest.mark.eval


def _skip_unless_ready() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip("LLM_PROVIDER not set; run `make eval-recommendation` for real")
    if not CHUNKS_JSONL_PATH.exists():
        pytest.skip("build/chunks.jsonl not built; run `make build-chunks`")
    try:
        import sentence_transformers  # noqa: F401
    except ImportError:
        pytest.skip("optional `embed` group not installed; `uv sync --group embed`")
    from infrastructure.database import (
        create_engine_from_settings,
        create_session_factory,
    )
    from infrastructure.database.models import ChunkRow

    try:
        engine = create_engine_from_settings()
        with create_session_factory(engine=engine)() as session:
            embedded = session.execute(
                select(func.count())
                .select_from(ChunkRow)
                .where(ChunkRow.embedding.is_not(None))
            ).scalar_one()
        engine.dispose()
    except Exception as exc:  # noqa: BLE001 - any DB failure is a skip, not a fail
        pytest.skip(f"database not ready for the recommendation eval: {exc}")
    if embedded < 100:
        pytest.skip(f"only {embedded} embedded chunks; run `make embed-chunks`")


@pytest.mark.eval
def test_recommendation_node_holds_its_structural_guarantees() -> None:
    _skip_unless_ready()

    from scripts.eval_recommendation import run_recommendation_eval

    result = run_recommendation_eval()

    assert result.error_question_ids == []
    assert result.n_scored >= 40
    # Every recommendation clause id was returned by retrieval.
    assert result.citation_grounding_rate == 1.0
    # An insufficient_information posture never carries a confident recommendation.
    if result.insufficient_posture_max_confidence is not None:
        assert (
            result.insufficient_posture_max_confidence
            <= _INSUFFICIENT_CONFIDENCE_CEILING
        )
    # The consistency signals are carried into the recommendation verbatim.
    assert result.flag_pass_through_rate == 1.0
