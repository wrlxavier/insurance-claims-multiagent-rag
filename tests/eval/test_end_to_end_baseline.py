"""Live re-check of the [M4-10] end-to-end run over the synthetic claims.

The unit tests cover the pieces with fakes: the verdict arithmetic
(``tests/unit/infrastructure/evaluation/test_verdict_metrics.py``), the judge
(``test_judge.py``), the rendered-reasoning round trip
(``tests/unit/infrastructure/graph/test_reasoning_format.py``) and the citation
gate (``tests/unit/scripts/test_validate_citation_coverage.py``). This
eval-marked test runs the **real** graph over the **real** claim set and pins
the two properties that are M4 exit criteria rather than bets:

- the graph completes on every claim, reaching and passing the human checkpoint;
- every recommendation citation was produced upstream.

Accuracy is a **bet**, not an invariant -- ``MILESTONES.md`` calls ≥75% a
reference value and says a milestone may close with a bad number that is
explained. The floor below is therefore set well under the published figure: it
guards against a collapse, not against a few points of drift. The authoritative
numbers are in ``docs/END_TO_END_EVALUATION.md``, regenerated by
``make eval-end-to-end``.

Needs ``LLM_PROVIDER`` set, ``build/chunks.jsonl``, a reachable Postgres with
embedded chunks, and the optional ``embed`` uv group. Skips cleanly when any is
absent, so ``make test-eval`` stays green (and free) on an unconfigured machine.
This is the most expensive eval in the suite -- it runs the whole graph 51
times -- so it is never part of the pre-commit or CI gate.
"""

import os

import pytest
from sqlalchemy import func, select

from infrastructure.rag.chunk_artifact import CHUNKS_JSONL_PATH

pytestmark = pytest.mark.eval

# Deliberately far below the published accuracy (56.9% overall, 45.5% on the
# mismatch cohort, run of 2026-09-02): a regression that matters is a collapse,
# and a floor set at the last run's number would fail on ordinary model variance
# rather than on a real problem. One claim moves the overall rate by ~2 points
# and the mismatch cohort by ~9, so these sit roughly 12 and 25 points low.
_ACCURACY_FLOOR = 0.45
# The mismatch cohort is the one the corpus was built to test; it is scored on
# its own so a good average cannot hide it going back to the zero it scored
# before the [M4-10] `_build_filter` fix.
_MISMATCH_ACCURACY_FLOOR = 0.20


def _skip_unless_ready() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip("LLM_PROVIDER not set; run `make eval-end-to-end` for real")
    if not CHUNKS_JSONL_PATH.exists():
        pytest.skip("build/chunks.jsonl not built; run `make build-chunks`")
    try:
        import sentence_transformers  # noqa: F401
    except ImportError:
        pytest.skip("optional `embed` group not installed; `uv sync --group embed`")
    from infrastructure.database import (
        create_engine_from_settings,
        create_session_factory,
    )
    from infrastructure.database.models import ChunkRow

    try:
        engine = create_engine_from_settings()
        with create_session_factory(engine=engine)() as session:
            embedded = session.execute(
                select(func.count())
                .select_from(ChunkRow)
                .where(ChunkRow.embedding.is_not(None))
            ).scalar_one()
        engine.dispose()
    except Exception as exc:  # noqa: BLE001 - any DB failure is a skip, not a fail
        pytest.skip(f"database not ready for the end-to-end eval: {exc}")
    if embedded < 100:
        pytest.skip(f"only {embedded} embedded chunks; run `make embed-chunks`")


@pytest.mark.eval
def test_the_graph_completes_and_stays_grounded_on_every_synthetic_claim() -> None:
    _skip_unless_ready()

    from scripts.eval_end_to_end import failure_cause, run_end_to_end_eval

    result = run_end_to_end_eval(policy_header=True, judge=False)

    # --- M4 exit criteria: invariants, asserted strictly -------------------
    assert result.error_claim_ids == []
    assert result.n_scored == 51, "the finalized claim set is 40 + 11"
    # "The graph completes on 100% of the synthetic claim set with no unhandled
    # exceptions", and nothing reaches a final state without the checkpoint.
    assert result.completion_rate == 1.0
    for row in result.results:
        assert row.reached_checkpoint, f"{row.claim_id} never reached human_review"
        retrieved = set(row.retrieved_clause_ids)
        assert set(row.recommendation_citation_ids) <= retrieved, (
            f"{row.claim_id} recommends a clause retrieval never returned"
        )

    # --- accuracy: a floor against collapse, not a target ------------------
    assert result.overall.accuracy >= _ACCURACY_FLOOR
    mismatch = result.by_cohort.get("mismatch")
    assert mismatch is not None, "the product/claim mismatch cohort must be scored"
    assert mismatch.accuracy >= _MISMATCH_ACCURACY_FLOOR

    # --- the catalogue partitions the wrong answers, with nothing left over -
    wrong = [r for r in result.results if r.error is None and not r.correct]
    assert sum(result.failure_causes.values()) == len(wrong)
    assert all(failure_cause(r) is not None for r in wrong)
    assert all(failure_cause(r) is None for r in result.results if r.correct), (
        "a correct verdict must not be catalogued as a failure"
    )
