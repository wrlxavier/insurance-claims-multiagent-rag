"""Sanity floor for the [M4-05] compatibility node against ``golden-set-v1``.

The unit tests (``tests/unit/infrastructure/graph/test_compatibility.py``) cover
the node's shape with a fake LLM. This eval-marked test is the on-demand
accuracy check the DoD asks for: it runs the real retrieval node + the real
compatibility node (on the reasoning model) over the verdict-labelled golden
questions and asserts a few conservative floors. The authoritative numbers --
the confusion matrix, per-class precision/recall, reference overlap -- are in
``eval/runs/compatibility.md``, regenerated by ``make eval-compatibility``. Full
three-class accuracy over the synthetic claims is [M4-10]'s.

Needs ``LLM_PROVIDER`` set, ``build/chunks.jsonl``, a reachable Postgres with
embedded chunks, and the optional ``embed`` uv group. Skips cleanly when any is
absent, so ``make test-eval`` stays green (and free) on an unconfigured machine.

Floors are deliberately loose -- a target is a bet, and the analysis in the
committed report is the deliverable.
"""

import os

import pytest
from sqlalchemy import func, select

from infrastructure.rag.chunk_artifact import CHUNKS_JSONL_PATH

pytestmark = pytest.mark.eval

_ACCURACY_FLOOR = 0.55
_INCOMPATIBLE_RECALL_FLOOR = 0.35
_INSUFFICIENT_RECALL_FLOOR = 0.45


def _skip_unless_ready() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip("LLM_PROVIDER not set; run `make eval-compatibility` for real")
    if not CHUNKS_JSONL_PATH.exists():
        pytest.skip("build/chunks.jsonl not built; run `make build-chunks`")
    try:
        import sentence_transformers  # noqa: F401
    except ImportError:
        pytest.skip("optional `embed` group not installed; `uv sync --group embed`")
    from infrastructure.database import (
        create_engine_from_settings,
        create_session_factory,
    )
    from infrastructure.database.models import ChunkRow

    try:
        engine = create_engine_from_settings()
        with create_session_factory(engine=engine)() as session:
            embedded = session.execute(
                select(func.count())
                .select_from(ChunkRow)
                .where(ChunkRow.embedding.is_not(None))
            ).scalar_one()
        engine.dispose()
    except Exception as exc:  # noqa: BLE001 - any DB failure is a skip, not a fail
        pytest.skip(f"database not ready for the compatibility eval: {exc}")
    if embedded < 100:
        pytest.skip(f"only {embedded} embedded chunks; run `make embed-chunks`")


@pytest.mark.eval
def test_compatibility_node_clears_a_verdict_floor_and_grounds_its_citations() -> None:
    _skip_unless_ready()

    from scripts.eval_compatibility import run_compatibility_eval

    result = run_compatibility_eval()

    assert result.error_question_ids == []
    assert result.overall.n >= 40
    assert result.overall.accuracy >= _ACCURACY_FLOOR
    assert (
        result.overall.per_class["incompatible"]["recall"] >= _INCOMPATIBLE_RECALL_FLOOR
    )
    assert (
        result.overall.per_class["insufficient_information"]["recall"]
        >= _INSUFFICIENT_RECALL_FLOOR
    )
    # Every emitted assessment is clause-grounded (the node enforces this).
    assert all(row.every_assertion_grounded for row in result.results)
