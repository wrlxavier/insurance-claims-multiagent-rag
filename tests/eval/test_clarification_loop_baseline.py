"""Live re-run of the [M4-03] clarification-loop measurement.

The unit tests (``tests/unit/infrastructure/graph/test_claim_graph.py``) prove
loop termination structurally with a fake LLM. This eval-marked test is the
on-demand live check: it runs the real fast model over the incomplete synthetic
claims and asserts a few conservative floors. The authoritative numbers -- the
generated questions, the live rounds distribution -- are in
``eval/runs/clarification_loop.md``, regenerated by ``make eval-clarification``.

Skips cleanly unless ``LLM_PROVIDER`` is set, so ``make test-eval`` stays green
(and free) on an unconfigured machine.
"""

import os

import pytest

pytestmark = pytest.mark.eval

# Deliberately loose -- a target is a bet, and the committed report is the
# deliverable. These only catch a grossly broken prompt or router.
_GENERIC_PHRASING_CEILING = 0.30


@pytest.mark.eval
def test_clarification_loop_runs_over_every_incomplete_claim_live() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip(
            "LLM_PROVIDER not set; run `make eval-clarification` for the real thing"
        )

    from scripts.eval_clarification import CLAIMS_PATH, run_clarification_eval

    if not CLAIMS_PATH.exists():
        pytest.skip(f"{CLAIMS_PATH} missing")

    result = run_clarification_eval()
    s = result.summary

    assert s.error_claim_ids == []
    assert s.n_claims >= 10  # DoD: ≥10 incomplete claims from [M2-04]
    # Every claim's graph run must terminate, whether or not it entered the loop.
    assert s.live_terminated == s.n_claims
    # A forced clarification call must produce one question per claim.
    assert s.questions_generated >= s.n_claims
    assert s.generic_flagged <= _GENERIC_PHRASING_CEILING * s.n_claims
