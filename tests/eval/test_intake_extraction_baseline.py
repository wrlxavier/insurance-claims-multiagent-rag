"""Live re-run of the [M4-02] intake-node extraction measurement.

The unit tests (``tests/unit/infrastructure/graph/test_intake.py``) cover the
node's shape with a fake LLM. This eval-marked test is the on-demand accuracy
check the DoD asks for: it runs the real fast model over every synthetic claim
and asserts the run completes with a few conservative floors. The authoritative
numbers -- product-line accuracy, missing-info recall/false-positive rate, field
population -- are in ``eval/runs/intake_extraction.md``, regenerated by
``make eval-intake``. The end-to-end verdict/citation gate is [M4-10]'s.

Skips cleanly unless ``LLM_PROVIDER`` is set, so ``make test-eval`` stays green
(and free) on an unconfigured machine.
"""

import os

import pytest

pytestmark = pytest.mark.eval

# Deliberately low -- a target is a bet, and the analysis in the committed
# report is the deliverable. These only catch a gross regression (the prompt
# broken, the model returning nothing).
_COMPATIBLE_PRODUCT_LINE_FLOOR = 0.60
_MISSING_FACT_RECALL_FLOOR = 0.30


@pytest.mark.eval
def test_intake_processes_every_synthetic_claim_live() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip("LLM_PROVIDER not set; run `make eval-intake` for the real thing")

    from scripts.eval_intake import CLAIM_PATHS, run_intake_eval

    for path in CLAIM_PATHS:
        if not path.exists():
            pytest.skip(f"{path} missing")

    result = run_intake_eval()
    summary = result.summary

    assert summary.error_claim_ids == []
    assert summary.processed >= 40
    compatible = summary.product_line.by_verdict_cohort["compatible"]
    assert compatible.accuracy >= _COMPATIBLE_PRODUCT_LINE_FLOOR
    assert summary.missing_info.missing_fact_type_recall >= _MISSING_FACT_RECALL_FLOOR
