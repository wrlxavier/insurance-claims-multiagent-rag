"""Live re-run of the [M4-06] consistency-node measurement.

The unit tests (``tests/unit/infrastructure/graph/test_consistency_checks.py``
and ``test_consistency.py``) cover every deterministic check in isolation and
the node's shape with a fake LLM. This eval-marked test is the on-demand live
check: it runs the real fast model (intake + the consistency node) over every
synthetic claim and asserts the run completes with a couple of conservative
floors. The authoritative distributions -- deterministic false-positive rate,
signal counts by check and cohort, the LLM category spread -- are in
``eval/runs/consistency.md``, regenerated by ``make eval-consistency``.

Skips cleanly unless ``LLM_PROVIDER`` is set, so ``make test-eval`` stays green
(and free) on an unconfigured machine. No Postgres / embed group: the
consistency node touches no retrieval stack.
"""

import os

import pytest

pytestmark = pytest.mark.eval

# Deliberately loose -- a target is a bet, and the committed report is the
# deliverable. This only catches a gross regression: the deterministic guard
# rails misfiring on coherent claims, or the node failing outright.
_COMPATIBLE_DETERMINISTIC_FALSE_POSITIVE_CEILING = 0.15


@pytest.mark.eval
def test_consistency_node_processes_every_synthetic_claim_live() -> None:
    if not os.environ.get("LLM_PROVIDER"):
        pytest.skip(
            "LLM_PROVIDER not set; run `make eval-consistency` for the real thing"
        )

    from scripts.eval_consistency import CLAIM_PATHS, run_consistency_eval

    for path in CLAIM_PATHS:
        if not path.exists():
            pytest.skip(f"{path} missing")

    result = run_consistency_eval()
    summary = result.summary

    assert summary.error_claim_ids == []
    assert summary.processed >= 40
    # every processed claim produced a report -- error_claim_ids == [] already
    # implies this, but assert on the cohort tally too
    assert sum(m.n for m in summary.by_cohort.values()) == summary.processed
    assert (
        summary.compatible_deterministic_false_positive_rate
        <= _COMPATIBLE_DETERMINISTIC_FALSE_POSITIVE_CEILING
    )
